using System;
using System.Collections.Generic;
using UnityEngine;

namespace BetterTogether.UI
{
    /// <summary>
    /// Scene-side description of the area the camp plan covers (C9.5, redone by C9.6): the hand-drawn paper picture, the world
    /// rectangle it shows (XZ plane), the two fixed points (fire and cage) and the names of the sectors. No network: it is
    /// plain scene data. A scene without one has no plan.
    /// </summary>
    public class MinimapArea : MonoBehaviour
    {
        /// <summary>A fixed point of interest drawn with the game icon of <see cref="Icon"/>.</summary>
        [Serializable]
        public struct FixedPoint
        {
            [Tooltip("World position on the XZ plane (x, z).")]
            public Vector2 Position;
            [Tooltip("Icon drawn at the point (Fire or Cage).")]
            public UiIcon Icon;
        }

        /// <summary>A sector name written on the plan.</summary>
        [Serializable]
        public struct SectorLabel
        {
            [Tooltip("Text written on the plan (Spanish, shown to the player).")]
            public string Text;
            [Tooltip("World position on the XZ plane (x, z) of the centre of the text.")]
            public Vector2 Position;
        }

        private static readonly List<MinimapArea> Registered = new();

        [Tooltip("Hand-drawn picture of the level, generated by the level builder.")]
        [SerializeField] private Texture2D _map;
        [Tooltip("World position (x, z) of the centre of the picture.")]
        [SerializeField] private Vector2 _worldCenter;
        [Tooltip("World size (x, z) in metres covered by the picture.")]
        [SerializeField] private Vector2 _worldSize = new(78f, 72f);
        [Tooltip("Fixed points of interest: fire and cage only.")]
        [SerializeField] private FixedPoint[] _points;
        [Tooltip("Names of the sectors, written on the plan.")]
        [SerializeField] private SectorLabel[] _labels;

        /// <summary>The area of the loaded scene, or null when the scene has none.</summary>
        public static MinimapArea Current => Registered.Count > 0 ? Registered[Registered.Count - 1] : null;

        public Texture2D Map => _map;
        public Vector2 WorldCenter => _worldCenter;
        public Vector2 WorldSize => _worldSize;
        public IReadOnlyList<FixedPoint> Points => _points;
        public IReadOnlyList<SectorLabel> Labels => _labels;

        private void OnEnable()
        {
            if (!Registered.Contains(this))
                Registered.Add(this);
        }

        private void OnDisable() => Registered.Remove(this);
    }
}
